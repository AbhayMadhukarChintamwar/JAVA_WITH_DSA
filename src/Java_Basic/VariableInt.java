package Java_Basic;

public class VariableInt {
    static void main(String[] args) {

        //variable(int)

        int x = 20; // declaration and initialization
        int y; // declaration
        y = 5; // initialization
        System.out.println(x + " " + y);
        System.out.println(x + y);
        System.out.println(x - y);
        System.out.println(x * y);
        System.out.println(x / y);

        // In the java language we can't declare value again in the same function. but we can initialize lots of times.

        x = 30;
        y = 6;
        System.out.println(x + " " + y);
        System.out.println(x + y);
        System.out.println(x - y);
        System.out.println(x * y);
        System.out.println(x / y);



    }
}
